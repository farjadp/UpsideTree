-- Upside Tree — Schema Sync CORRECTION
--
-- WHY THIS EXISTS
-- 20260816000000_sync_live_schema.sql was supposed to create all 18 missing
-- tables verbatim from schema.sql. While assembling that file, several of
-- the "supporting" tables (media_library, product_variants,
-- product_attributes, product_tags, carts, cart_items, coupons,
-- shipping_zones, tax_rates, restock_notifications, media_assets,
-- navigation_menus, announcement_bars, redirects, custom_scripts) were
-- hand-typed from memory instead of copied verbatim from schema.sql, and
-- drifted from the intended schema on day one — e.g. cart_items got
-- `price_at_add` instead of the real `unit_price` + `product_snapshot`
-- columns, which is what src/app/api/cart/route.ts actually writes to.
-- That mismatch has been silently breaking cart persistence since the
-- first migration ran.
--
-- This migration was generated by extracting the CREATE TABLE statements
-- directly from schema.sql via script (not retyped), to remove any more
-- risk of transcription error.
--
-- SAFETY
-- All 18 tables were confirmed empty (0 rows) in production immediately
-- before writing this migration, so it safely DROPs and recreates them
-- verbatim from schema.sql rather than patching column-by-column — an
-- exact match with zero ambiguity. Nothing outside these 18 tables is
-- touched; products/collections/orders/order_items (which were correctly
-- generated the first time) are untouched here.
-- ============================================================================

